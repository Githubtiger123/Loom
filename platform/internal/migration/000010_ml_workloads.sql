-- Domain records are deliberately separate from execution operations.
-- No permissions are seeded here, the integration migration owns that dictionary.
CREATE TABLE tb_pipeline (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  group_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  display_name VARCHAR(128) NOT NULL DEFAULT '',
  description VARCHAR(1000) NOT NULL DEFAULT '',
  created_by BIGINT UNSIGNED DEFAULT NULL,
  revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_pipeline_name (group_id, name),
  KEY idx_pipeline_owner (group_id, created_by, id),
  CONSTRAINT ck_pipeline_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_pipeline_version (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  group_id BIGINT UNSIGNED NOT NULL,
  pipeline_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  spec JSON NOT NULL,
  spec_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_pipeline_version_name (group_id, pipeline_id, name),
  KEY idx_pipeline_version_page (group_id, pipeline_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_pipeline_run (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  group_id BIGINT UNSIGNED NOT NULL,
  pipeline_id BIGINT UNSIGNED NOT NULL,
  version_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  instance_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cluster VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  namespace VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  external_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
  applied_revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
  desired_state VARCHAR(24) NOT NULL,
  observed_state VARCHAR(24) NOT NULL DEFAULT 'UNKNOWN',
  status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  status_reason VARCHAR(1024) DEFAULT NULL,
  requested_spec JSON NOT NULL,
  last_operation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  observed_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_pipeline_run_instance (instance_id),
  UNIQUE KEY uk_pipeline_run_external (cluster, external_id),
  KEY idx_pipeline_run_owner (group_id, created_by, id),
  KEY idx_pipeline_run_definition (group_id, pipeline_id, id),
  KEY idx_pipeline_run_operation (last_operation_id),
  CONSTRAINT ck_pipeline_run_revision CHECK (revision > 0 AND applied_revision <= revision),
  CONSTRAINT ck_pipeline_run_desired CHECK (desired_state IN ('RUNNING','STOPPED')),
  CONSTRAINT ck_pipeline_run_observed CHECK (observed_state IN ('UNKNOWN','PENDING','RUNNING','SUCCEEDED','FAILED','STOPPED')),
  CONSTRAINT ck_pipeline_run_status CHECK (status IN ('UNKNOWN','PENDING','RUNNING','SUCCEEDED','FAILED','STOPPED','ERROR'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

