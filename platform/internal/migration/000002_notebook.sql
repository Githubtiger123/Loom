CREATE TABLE tb_notebook (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  instance_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  cluster VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  namespace VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  group_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  uid CHAR(36) CHARACTER SET ascii DEFAULT NULL,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  display_name VARCHAR(128) NOT NULL DEFAULT '',
  description VARCHAR(1000) NOT NULL DEFAULT '',
  image VARCHAR(512) NOT NULL,
  image_id VARCHAR(64) NOT NULL,
  cpu_milli BIGINT NOT NULL,
  memory_bytes BIGINT NOT NULL,
  gpu_count INT UNSIGNED NOT NULL DEFAULT 0,
  workspace_pvc VARCHAR(63) CHARACTER SET ascii NOT NULL,
  workspace_uid CHAR(36) CHARACTER SET ascii DEFAULT NULL,
  workspace_size_bytes BIGINT NOT NULL,
  idle_stop_minutes INT UNSIGNED NOT NULL DEFAULT 0,
  requested_spec JSON NOT NULL,
  observed_spec JSON DEFAULT NULL,
  desired_state VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
  status VARCHAR(32) NOT NULL DEFAULT 'CREATING',
  status_reason VARCHAR(1024) DEFAULT NULL,
  revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
  observed_at DATETIME(3) DEFAULT NULL,
  last_active_at DATETIME(3) DEFAULT NULL,
  started_at DATETIME(3) DEFAULT NULL,
  stopped_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_instance (instance_id),
  UNIQUE KEY uk_notebook_name (cluster, namespace, name),
  KEY idx_notebook_group (group_id, status, id),
  KEY idx_notebook_creator (created_by, group_id, id),
  CONSTRAINT ck_notebook_desired CHECK (desired_state IN ('RUNNING','STOPPED','DELETED')),
  CONSTRAINT ck_notebook_resources CHECK (cpu_milli > 0 AND memory_bytes > 0 AND workspace_size_bytes > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
