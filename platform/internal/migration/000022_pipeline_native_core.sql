CREATE TABLE tb_pipeline_task_execution (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  group_id BIGINT UNSIGNED NOT NULL,
  run_id BIGINT UNSIGNED NOT NULL,
  instance_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  definition_path TEXT NOT NULL,
  parent_id BIGINT UNSIGNED DEFAULT NULL,
  iteration_path JSON NOT NULL,
  retry_index INT UNSIGNED NOT NULL DEFAULT 0,
  node_kind VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  argo_node_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  pod_name VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  pod_uid VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  phase VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING',
  reason VARCHAR(1024) DEFAULT NULL,
  inputs JSON NOT NULL,
  outputs JSON NOT NULL,
  cache_source_task_id BIGINT UNSIGNED DEFAULT NULL,
  runtime_state JSON DEFAULT NULL,
  writer_epoch BIGINT UNSIGNED NOT NULL DEFAULT 0,
  report_sequence BIGINT UNSIGNED NOT NULL DEFAULT 0,
  report_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  observation_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  started_at DATETIME(3) DEFAULT NULL,
  finished_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_pipeline_task_node (group_id, instance_id, node_key),
  UNIQUE KEY uk_pipeline_task_argo_node (group_id, instance_id, argo_node_id),
  UNIQUE KEY uk_pipeline_task_scope (group_id, instance_id, id),
  UNIQUE KEY uk_pipeline_task_group_id (group_id, id),
  KEY idx_pipeline_task_attempt (group_id, run_id, instance_id),
  KEY idx_pipeline_task_parent (group_id, instance_id, parent_id, id),
  KEY idx_pipeline_task_phase (group_id, instance_id, phase, id),
  KEY idx_pipeline_task_cache_source (group_id, cache_source_task_id),
  CONSTRAINT fk_pipeline_task_attempt FOREIGN KEY (group_id, run_id, instance_id)
    REFERENCES tb_pipeline_run_attempt (group_id, run_id, instance_id),
  CONSTRAINT fk_pipeline_task_parent FOREIGN KEY (group_id, instance_id, parent_id)
    REFERENCES tb_pipeline_task_execution (group_id, instance_id, id),
  CONSTRAINT fk_pipeline_task_cache_source FOREIGN KEY (group_id, cache_source_task_id)
    REFERENCES tb_pipeline_task_execution (group_id, id),
  CONSTRAINT ck_pipeline_task_phase CHECK (phase IN ('UNKNOWN','PENDING','RUNNING','PAUSED','SUCCEEDED','FAILED','STOPPED','SKIPPED','CACHED','ERROR')),
  CONSTRAINT ck_pipeline_task_kind CHECK (node_kind IN ('DAG','CONTAINER','CONDITION','LOOP','RETRY','IMPORTER','EXIT_HANDLER','LOGICAL')),
  CONSTRAINT ck_pipeline_task_iteration CHECK (JSON_TYPE(iteration_path)='ARRAY'),
  CONSTRAINT ck_pipeline_task_inputs CHECK (JSON_TYPE(inputs)='OBJECT'),
  CONSTRAINT ck_pipeline_task_outputs CHECK (JSON_TYPE(outputs)='OBJECT'),
  CONSTRAINT ck_pipeline_task_runtime CHECK (runtime_state IS NULL OR JSON_TYPE(runtime_state)='OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE tb_pipeline_artifact (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  group_id BIGINT UNSIGNED NOT NULL,
  producer_instance_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  producer_task_id BIGINT UNSIGNED DEFAULT NULL,
  registration_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  type_name VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  type_schema_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  type_schema JSON NOT NULL,
  type_schema_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  uri TEXT DEFAULT NULL,
  object_ref JSON DEFAULT NULL,
  metadata JSON NOT NULL,
  visualizations JSON NOT NULL,
  provenance JSON NOT NULL,
  state VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'STAGING',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  published_at DATETIME(3) DEFAULT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_pipeline_artifact_registration (group_id, registration_key),
  KEY idx_pipeline_artifact_producer (group_id, producer_task_id, id),
  KEY idx_pipeline_artifact_producer_scope (group_id, producer_instance_id, producer_task_id),
  KEY idx_pipeline_artifact_type (group_id, type_name, created_at, id),
  CONSTRAINT fk_pipeline_artifact_producer FOREIGN KEY (group_id, producer_instance_id, producer_task_id)
    REFERENCES tb_pipeline_task_execution (group_id, instance_id, id),
  CONSTRAINT ck_pipeline_artifact_producer CHECK ((producer_instance_id IS NULL) = (producer_task_id IS NULL)),
  CONSTRAINT ck_pipeline_artifact_state CHECK (state IN ('STAGING','PUBLISHED','FAILED','UNAVAILABLE')),
  CONSTRAINT ck_pipeline_artifact_published CHECK (state <> 'PUBLISHED' OR
    (uri IS NOT NULL AND CHAR_LENGTH(uri) > 0 AND object_ref IS NOT NULL AND published_at IS NOT NULL)),
  CONSTRAINT ck_pipeline_artifact_schema CHECK (JSON_TYPE(type_schema)='OBJECT'),
  CONSTRAINT ck_pipeline_artifact_object CHECK (object_ref IS NULL OR JSON_TYPE(object_ref)='OBJECT'),
  CONSTRAINT ck_pipeline_artifact_metadata CHECK (JSON_TYPE(metadata)='OBJECT'),
  CONSTRAINT ck_pipeline_artifact_visualizations CHECK (JSON_TYPE(visualizations)='ARRAY'),
  CONSTRAINT ck_pipeline_artifact_provenance CHECK (JSON_TYPE(provenance)='OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
